"""Builds property-chat.js, the single file to embed on a website.

    python web/free-widget/build.py

Combines ../engine.js (the calculator) with chat-ui.js (the guided chat) inside one wrapper.
"""
from pathlib import Path

here = Path(__file__).parent
engine = (here.parent / "engine.js").read_text(encoding="utf-8")
ui = (here / "chat-ui.js").read_text(encoding="utf-8")
header = """/*
 * Free property chat widget: guided questions, no AI, no server, no API key.
 * Add to any website just before </body>:
 *   <script src="property-chat.js" data-color="#0d6b5a" data-name="Your Agency" data-whatsapp="6590000000" defer></script>
 * Optional: data-webhook="https://script.google.com/macros/s/.../exec" sends leads to a Google Sheet.
 * Generated by build.py from ../engine.js and chat-ui.js. Edit those, not this file.
 */
"""
out = header + "(function () {\n  if (window.__propertyChatLoaded) return;\n  window.__propertyChatLoaded = true;\n\n" + engine + "\n\n" + ui + "\n})();\n"
(here / "property-chat.js").write_text(out, encoding="utf-8")
print(f"wrote property-chat.js ({len(out):,} bytes)")
